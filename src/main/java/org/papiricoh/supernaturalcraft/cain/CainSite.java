package org.papiricoh.supernaturalcraft.cain;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.QuartPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.LevelHeightAccessor;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.RandomState;
import org.papiricoh.supernaturalcraft.SupernaturalCraft;
import org.papiricoh.supernaturalcraft.coven.rowena.RowenaRing;

import java.util.Map;
import java.util.WeakHashMap;

/**
 * Which of the {@link CainRing} candidates holds Cain's farm (v0.21), worked out the same way by the world generator (in
 * {@link CainFarmStructure}) and from the live world (his address, Rowena's clue): the first candidate on quiet, flat, dry
 * ground in farm country ({@link #BIOMES}). Remembered per {@link RandomState}.
 */
public final class CainSite {

    /** Where his farm may stand (generated by datagen: plains, meadows, sunflower plains, forest edges). */
    public static final TagKey<Biome> BIOMES = TagKey.create(Registries.BIOME, SupernaturalCraft.asResource("cain_farm_biomes"));
    /** How far from the middle the corners are sampled for flatness. */
    private static final int REACH = 14;
    private static final Map<RandomState, Integer> CHOSEN = new WeakHashMap<>();

    /** Where the farm stands: its origin (the yard's middle on the ground, first air above it) and turn. */
    public record Site(BlockPos origin, int rotation) {
    }

    private CainSite() {
    }

    public static int chosen(long seed, ChunkGenerator generator, BiomeSource biomes, RandomState random, LevelHeightAccessor heights) {
        synchronized (CHOSEN) {
            Integer known = CHOSEN.get(random);
            if (known != null) return known;
        }
        int[][] chunks = CainPlacement.candidates(seed);
        // The two rings overlap: never a farm within MIN_FROM_ROWENA blocks of Rowena's house.
        int[] rowena = org.papiricoh.supernaturalcraft.coven.rowena.RowenaPlacement.candidates(seed)[
                org.papiricoh.supernaturalcraft.coven.rowena.RowenaSite.chosen(seed, generator, biomes, random, heights)];
        int rx = RowenaRing.middle(rowena[0]), rz = RowenaRing.middle(rowena[1]);
        int k = RowenaRing.choose(i -> farFrom(chunks[i], rx, rz) && quiet(chunks[i], generator, biomes, random, heights));
        synchronized (CHOSEN) {
            CHOSEN.put(random, k);
        }
        return k;
    }

    /** The fewest blocks between Cain's farm and Rowena's house. */
    public static final int MIN_FROM_ROWENA = 400;

    /** Whether the candidate {@code chunk} lies at least {@link #MIN_FROM_ROWENA} blocks from Rowena's house at ({@code rx}, {@code rz}). */
    public static boolean farFrom(int[] chunk, int rx, int rz) {
        double dx = RowenaRing.middle(chunk[0]) - rx, dz = RowenaRing.middle(chunk[1]) - rz;
        return dx * dx + dz * dz >= (double) MIN_FROM_ROWENA * MIN_FROM_ROWENA;
    }

    static boolean quiet(int[] chunk, ChunkGenerator generator, BiomeSource biomes, RandomState random, LevelHeightAccessor heights) {
        int x = RowenaRing.middle(chunk[0]), z = RowenaRing.middle(chunk[1]);
        int[][] at = {{0, 0}, {-REACH, -REACH}, {REACH, -REACH}, {-REACH, REACH}, {REACH, REACH}};
        int[] tops = new int[at.length], floors = new int[at.length];
        for (int i = 0; i < at.length; i++) {
            tops[i] = generator.getBaseHeight(x + at[i][0], z + at[i][1], Heightmap.Types.WORLD_SURFACE_WG, heights, random);
            floors[i] = generator.getBaseHeight(x + at[i][0], z + at[i][1], Heightmap.Types.OCEAN_FLOOR_WG, heights, random);
        }
        if (!RowenaRing.flat(tops, floors, generator.getSeaLevel())) return false;
        Holder<Biome> biome = biomes.getNoiseBiome(QuartPos.fromBlock(x), QuartPos.fromBlock(tops[0]), QuartPos.fromBlock(z), random.sampler());
        return biome.is(BIOMES);
    }

    /** Where the world generator puts (or would put) the farm, read from the live overworld. */
    public static Site compute(ServerLevel level) {
        var source = level.getChunkSource();
        ChunkGenerator generator = source.getGenerator();
        RandomState random = source.randomState();
        long seed = level.getSeed();
        int k = chosen(seed, generator, generator.getBiomeSource(), random, level);
        int[] chunk = CainPlacement.candidates(seed)[k];
        int x = RowenaRing.middle(chunk[0]), z = RowenaRing.middle(chunk[1]);
        int y = generator.getBaseHeight(x, z, Heightmap.Types.WORLD_SURFACE_WG, level, random);
        return new Site(new BlockPos(x, y, z), CainRing.rotation(seed));
    }

    /** The farm's site for this world, worked out once and remembered in {@link CainSavedData}. */
    public static Site of(ServerLevel level) {
        CainSavedData data = CainSavedData.get(level);
        if (data.farm() == null) {
            Site s = compute(level.getServer().overworld());
            data.setFarm(s.origin(), s.rotation(), false);
        }
        return new Site(data.farm(), data.rotation());
    }
}
