package org.papiricoh.supernaturalcraft.coven.rowena;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.QuartPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.LevelHeightAccessor;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.RandomState;
import org.papiricoh.supernaturalcraft.SupernaturalCraft;

import java.util.Map;
import java.util.WeakHashMap;

/**
 * Which of the {@link RowenaRing} candidates holds Rowena's house (v0.21), worked out the same way by the world generator (in
 * {@link RowenaHouseStructure}) and by her calling card (from the live world): the first candidate on quiet, flat, dry ground in
 * a forest-edge biome ({@link #BIOMES}). Remembered per {@link RandomState}.
 */
public final class RowenaSite {

    /** Where her house may stand (generated by datagen: forests, birch and flower forests, meadows, plains by the trees). */
    public static final TagKey<Biome> BIOMES = TagKey.create(Registries.BIOME, SupernaturalCraft.asResource("rowena_house_biomes"));
    /** How far from the middle the corners are sampled for flatness. */
    private static final int REACH = 9;
    /** How far out the front garden's middle lies (any turn): it must be as level as the house. */
    private static final int GARDEN = 22;
    private static final Map<RandomState, Integer> CHOSEN = new WeakHashMap<>();

    /** Where the house stands: its origin (the hall's floor centre, first air above the floor) and turn. */
    public record Site(BlockPos origin, int rotation) {
    }

    private RowenaSite() {
    }

    public static int chosen(long seed, ChunkGenerator generator, BiomeSource biomes, RandomState random, LevelHeightAccessor heights) {
        synchronized (CHOSEN) {
            Integer known = CHOSEN.get(random);
            if (known != null) return known;
        }
        int[][] chunks = RowenaPlacement.candidates(seed);
        int k = RowenaRing.choose(i -> quiet(chunks[i], generator, biomes, random, heights));
        synchronized (CHOSEN) {
            CHOSEN.put(random, k);
        }
        return k;
    }

    static boolean quiet(int[] chunk, ChunkGenerator generator, BiomeSource biomes, RandomState random, LevelHeightAccessor heights) {
        int x = RowenaRing.middle(chunk[0]), z = RowenaRing.middle(chunk[1]);
        // v0.21 (P6): and the front garden, wherever the door turns (her fight is there).
        int[][] at = {{0, 0}, {-REACH, -REACH}, {REACH, -REACH}, {-REACH, REACH}, {REACH, REACH},
                {0, GARDEN}, {0, -GARDEN}, {GARDEN, 0}, {-GARDEN, 0}};
        int[] tops = new int[at.length], floors = new int[at.length];
        for (int i = 0; i < at.length; i++) {
            tops[i] = generator.getBaseHeight(x + at[i][0], z + at[i][1], Heightmap.Types.WORLD_SURFACE_WG, heights, random);
            floors[i] = generator.getBaseHeight(x + at[i][0], z + at[i][1], Heightmap.Types.OCEAN_FLOOR_WG, heights, random);
        }
        if (!RowenaRing.flat(tops, floors, generator.getSeaLevel())) return false;
        Holder<Biome> biome = biomes.getNoiseBiome(QuartPos.fromBlock(x), QuartPos.fromBlock(tops[0]), QuartPos.fromBlock(z), random.sampler());
        return biome.is(BIOMES);
    }

    /** Where the world generator puts (or would put) the house, read from the live overworld. */
    public static Site compute(ServerLevel level) {
        var source = level.getChunkSource();
        ChunkGenerator generator = source.getGenerator();
        RandomState random = source.randomState();
        long seed = level.getSeed();
        int k = chosen(seed, generator, generator.getBiomeSource(), random, level);
        int[] chunk = RowenaPlacement.candidates(seed)[k];
        int x = RowenaRing.middle(chunk[0]), z = RowenaRing.middle(chunk[1]);
        int y = generator.getBaseHeight(x, z, Heightmap.Types.WORLD_SURFACE_WG, level, random);
        return new Site(new BlockPos(x, y, z), RowenaRing.rotation(seed));
    }

    /** The house's site for this world, worked out once and remembered in {@link RowenaSavedData}. */
    public static Site of(ServerLevel level) {
        RowenaSavedData data = RowenaSavedData.get(level);
        if (data.house() == null) {
            Site s = compute(level.getServer().overworld());
            data.setHouse(s.origin(), s.rotation(), false);
        }
        return new Site(data.house(), data.rotation());
    }
}
