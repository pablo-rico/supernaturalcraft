"""Writes tools/lang_fragments/darkness_core.py into DarknessLang.java (English) and es_es.json (Spanish, inserted/updated)."""
import json, re, sys, importlib.util, collections
spec = importlib.util.spec_from_file_location("core", "tools/lang_fragments/darkness_core.py")
core = importlib.util.module_from_spec(spec); spec.loader.exec_module(core)
spec2 = importlib.util.spec_from_file_location("story", "tools/lang_fragments/darkness_story.py")
story = importlib.util.module_from_spec(spec2); spec2.loader.exec_module(story)
core.ENTRIES = core.ENTRIES + story.ENTRIES
spec3 = importlib.util.spec_from_file_location("hints", "tools/lang_fragments/darkness_hints.py")
hints = importlib.util.module_from_spec(spec3); spec3.loader.exec_module(hints)
core.ENTRIES = core.ENTRIES + hints.ENTRIES
# The art agent's client text (titles, voices, HUD labels): {key: {en, es}}.
_client = json.load(open("tools/lang_fragments/amara_client.json", encoding="utf-8"))
core.ENTRIES = core.ENTRIES + [(k, v["en"], v["es"]) for k, v in _client.items()]
java = "src/main/java/org/papiricoh/supernaturalcraft/datagen/darkness/DarknessLang.java"
def q(s): return json.dumps(s, ensure_ascii=False)
NAMED = {"entity.supernaturalcraft.casifer", "entity.supernaturalcraft.chuck_ally", "entity.supernaturalcraft.amara_visitor", "entity.supernaturalcraft.fogged_villager", "item.supernaturalcraft.amaras_light"}
lines = "\n".join(f"        add.accept({q(k)}, {q(en)});" for k, en, es in core.ENTRIES if k not in NAMED)
src = open(java, encoding="utf-8").read()
src = re.sub(r"(static void add\(BiConsumer<String, String> add\) \{\n)(.*?)(\n    \}\n)", lambda m: m.group(1) + "        // generated by tools/lang_fragments/apply_core_lang.py from darkness_core.py\n" + lines + m.group(3), src, count=1, flags=re.S)
open(java, "w", encoding="utf-8").write(src)
p = "src/main/resources/assets/supernaturalcraft/lang/es_es.json"
es = json.loads(open(p, encoding="utf-8", newline="").read(), object_pairs_hook=collections.OrderedDict)
for k, en, sp in core.ENTRIES: es[k] = sp
open(p, "w", encoding="utf-8").write(json.dumps(es, ensure_ascii=False, indent=2) + "\n")
print(len(core.ENTRIES), "entries")
